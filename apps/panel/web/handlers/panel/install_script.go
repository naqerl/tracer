package panel

import (
	"fmt"
	"strings"
)

// installScriptURL is where a collector host fetches the installer from. The
// collector-only mode installs just the collector, so the panel itself is never
// installed on a remote host.
const installScriptURL = "https://git.naqerl.com/naqerl/tracer/raw/main/install.sh"

// shellQuote wraps a value in single quotes so a shell treats it literally.
// Single quotes suspend every expansion, including the ones inside the value.
// An embedded single quote is closed, escaped, and reopened.
func shellQuote(value string) string {
	return `'` + strings.ReplaceAll(value, `'`, `'\''`) + `'`
}

// renderCollectorInstallScript returns a self-contained bootstrap script that
// brings a host to a running collector: it installs the collector when the
// binary is missing, upgrades it when present, points it at this panel, and
// wires a kubeconfig so kubectl log sources work.
//
// Every value interpolated into the script goes through shellQuote, so a name
// or key containing shell metacharacters stays a single argument.
func renderCollectorInstallScript(collectorName, apiKey, panelHost, installURL string) string {
	var b strings.Builder

	fmt.Fprintf(&b, "#!/bin/bash\n")
	fmt.Fprintf(&b, "# Installs or upgrades the tracer collector and starts it.\n")
	fmt.Fprintf(&b, "# Generated by the tracer panel. Safe to re-run: it upgrades an\n")
	fmt.Fprintf(&b, "# existing collector and leaves its config in place.\n")
	fmt.Fprintf(&b, "set -euo pipefail\n\n")

	fmt.Fprintf(&b, "log() { printf '\\033[1;32m%%s\\033[0m\\n' \"$*\" >&2; }\n")
	fmt.Fprintf(&b, "die() { printf '\\033[1;31m%%s\\033[0m\\n' \"$*\" >&2; exit 1; }\n\n")

	fmt.Fprintf(&b, "[ \"$(id -u)\" -eq 0 ] || die \"This script must run as root: sudo bash\"\n")
	fmt.Fprintf(&b, "command -v curl >/dev/null 2>&1 || die \"curl is required\"\n\n")

	// The upgrade path replaces the running binary in place, so the unit must be
	// stopped first and the config is left untouched by the installer.
	fmt.Fprintf(&b, "UNIT=tracer-collector\n")
	fmt.Fprintf(&b, "if systemctl list-unit-files \"${UNIT}.service\" >/dev/null 2>&1 && systemctl cat \"${UNIT}.service\" >/dev/null 2>&1; then\n")
	fmt.Fprintf(&b, "\tlog \"Stopping ${UNIT}...\"\n")
	fmt.Fprintf(&b, "\tsystemctl stop \"${UNIT}\" || true\n")
	fmt.Fprintf(&b, "else\n")
	fmt.Fprintf(&b, "\tlog \"Collector is not installed yet\"\n")
	fmt.Fprintf(&b, "fi\n\n")

	fmt.Fprintf(&b, "log \"Installing tracer-collector...\"\n")
	fmt.Fprintf(&b, "curl -fsSL %s | \\\n", shellQuote(installURL))
	fmt.Fprintf(&b, "\tsudo TRACER_COLLECTOR_ONLY=1 \\\n")
	fmt.Fprintf(&b, "\tTRACER_COLLECTOR_NAME=%s \\\n", shellQuote(collectorName))
	fmt.Fprintf(&b, "\tTRACER_COLLECTOR_API_KEY=%s \\\n", shellQuote(apiKey))
	fmt.Fprintf(&b, "\tTRACER_COLLECTOR_PANEL_HOST=%s \\\n", shellQuote(panelHost))
	fmt.Fprintf(&b, "\tbash\n\n")

	fmt.Fprintf(&b, "log \"Configuring collector...\"\n")
	fmt.Fprintf(&b, "tracer-collector set name %s\n", shellQuote(collectorName))
	fmt.Fprintf(&b, "tracer-collector set api-key %s\n", shellQuote(apiKey))
	fmt.Fprintf(&b, "tracer-collector set panel-host %s\n\n", shellQuote(panelHost))

	// kubectl sources fail with a bare "permission denied" on the default
	// kubeconfig, so the collector gets its own copy of one it can read.
	fmt.Fprintf(&b, "if command -v kubectl >/dev/null 2>&1; then\n")
	fmt.Fprintf(&b, "\tlog \"Setting up kubectl access...\"\n")
	fmt.Fprintf(&b, "\ttracer-collector kubectl-setup || log \"Could not set up kubectl access; kubectl log sources may not work\"\n\n")
	fmt.Fprintf(&b, "fi\n\n")

	fmt.Fprintf(&b, "log \"Enabling and starting ${UNIT}...\"\n")
	fmt.Fprintf(&b, "systemctl daemon-reload\n")
	fmt.Fprintf(&b, "systemctl enable --now %s\n\n", shellQuote("tracer-collector.service"))
	fmt.Fprintf(&b, "log \"Verifying the collector can reach the panel...\"\n")
	fmt.Fprintf(&b, "tracer-collector verify\n\n")

	// One argument: log() prints "$*" verbatim and expands no format specifier.
	fmt.Fprintf(&b, "log %s\n", shellQuote("Collector "+collectorName+" is installed and running."))
	fmt.Fprintf(&b, "printf '\\nFollow its logs with:  journalctl -u %s -f\\n'\n", shellQuote("tracer-collector"))

	return b.String()
}
